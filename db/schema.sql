CREATE SEQUENCE SEQ_CUSTOMER START WITH 1000;
CREATE SEQUENCE SEQ_AUDIT_EVENT START WITH 1;

CREATE TABLE CUSTOMER (
  CUSTOMER_ID            NUMBER(19)          PRIMARY KEY,
  NAME                   VARCHAR2(50 CHAR)   NOT NULL,
  BIRTH_DATE             DATE                NOT NULL,
  RESIDENT_REG_NO        VARCHAR2(200)       NOT NULL,
  PHONE                  VARCHAR2(20)        NOT NULL,
  EMAIL                  VARCHAR2(100 CHAR)  NOT NULL,
  ADDRESS                VARCHAR2(200 CHAR)  NOT NULL,
  CREDIT_STATUS          VARCHAR2(20)        NOT NULL,
  COLLECTION_STATUS      VARCHAR2(20)        NOT NULL,
  ASSIGNED_CONSULTANT_ID VARCHAR2(36),
  CREATED_AT             TIMESTAMP           NOT NULL,
  UPDATED_AT             TIMESTAMP           NOT NULL
);
CREATE INDEX IX_CUSTOMER_CONSULTANT ON CUSTOMER (ASSIGNED_CONSULTANT_ID);

CREATE TABLE ACCOUNT (
  ACCOUNT_ID           VARCHAR2(36)       PRIMARY KEY,
  LOGIN_ID             VARCHAR2(30)       NOT NULL UNIQUE,
  CUSTOMER_ID          NUMBER(19)         UNIQUE REFERENCES CUSTOMER (CUSTOMER_ID),
  STAFF_NAME           VARCHAR2(50 CHAR),
  SIGNUP_REF           VARCHAR2(64)       UNIQUE,
  PASSWORD_HASH        VARCHAR2(100)      NOT NULL,
  ROLE                 VARCHAR2(20)       NOT NULL,
  STATUS               VARCHAR2(30)       NOT NULL,
  FAILED_LOGIN_COUNT   NUMBER(5)          DEFAULT 0 NOT NULL,
  SESSION_EPOCH        NUMBER(10)         DEFAULT 0 NOT NULL,
  IDENTITY_VERIFIED_AT TIMESTAMP,
  PASSWORD_CHANGED_AT  TIMESTAMP,
  LAST_LOGIN_AT        TIMESTAMP,
  CREATED_AT           TIMESTAMP          NOT NULL
);

CREATE TABLE SUBSCRIPTION (
  SUBSCRIPTION_ID NUMBER(19)   PRIMARY KEY,
  CUSTOMER_ID     NUMBER(19)   NOT NULL REFERENCES CUSTOMER (CUSTOMER_ID),
  PLAN_ID         NUMBER(19)   NOT NULL,
  LINE_NUMBER     VARCHAR2(20) NOT NULL,
  STATUS          VARCHAR2(20) NOT NULL,
  VERSION         NUMBER(10)   DEFAULT 1 NOT NULL
);
CREATE INDEX IX_SUBSCRIPTION_CUSTOMER ON SUBSCRIPTION (CUSTOMER_ID);

CREATE TABLE IDENTITY_VERIFICATION (
  VERIFICATION_ID   VARCHAR2(36)  PRIMARY KEY,
  ACCOUNT_ID        VARCHAR2(36)  NOT NULL REFERENCES ACCOUNT (ACCOUNT_ID),
  AGENCY_RESULT_REF VARCHAR2(200) UNIQUE,
  STATUS            VARCHAR2(20)  NOT NULL,
  EXPIRES_AT        TIMESTAMP     NOT NULL,
  COMPLETED_AT      TIMESTAMP,
  CREATED_AT        TIMESTAMP     NOT NULL
);

CREATE TABLE AUDIT_EVENT (
  EVENT_ID    NUMBER(19)         PRIMARY KEY,
  ACTOR_ID    VARCHAR2(36)       NOT NULL,
  ACTION      VARCHAR2(40)       NOT NULL,
  TARGET_TYPE VARCHAR2(20)       NOT NULL,
  TARGET_ID   VARCHAR2(200),
  CUSTOMER_ID NUMBER(19),
  REASON      VARCHAR2(500 CHAR),
  OCCURRED_AT TIMESTAMP          NOT NULL,
  RESULT      VARCHAR2(10)       NOT NULL,
  CLIENT_IP   VARCHAR2(45)
);
CREATE INDEX IX_AUDIT_EVENT_CUSTOMER ON AUDIT_EVENT (CUSTOMER_ID);

CREATE SEQUENCE SEQ_PASSWORD_RESET START WITH 1;
CREATE TABLE PASSWORD_RESET (
  RESET_ID    NUMBER(19)         PRIMARY KEY,
  ACCOUNT_ID  VARCHAR2(36)       NOT NULL REFERENCES ACCOUNT (ACCOUNT_ID),
  TOKEN_HASH  VARCHAR2(200)      NOT NULL UNIQUE,
  EXPIRES_AT  TIMESTAMP          NOT NULL,
  USED_AT     TIMESTAMP,
  CREATED_AT  TIMESTAMP          NOT NULL
);

CREATE SEQUENCE SEQ_MAIL_OUTBOX START WITH 1;
CREATE TABLE MAIL_OUTBOX (
  MAIL_ID     NUMBER(19)         PRIMARY KEY,
  TO_EMAIL    VARCHAR2(100 CHAR) NOT NULL,
  SUBJECT     VARCHAR2(200 CHAR) NOT NULL,
  BODY        VARCHAR2(1000 CHAR) NOT NULL,
  CREATED_AT  TIMESTAMP          NOT NULL
);

